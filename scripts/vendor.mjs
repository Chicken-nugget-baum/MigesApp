// Copies the browser builds of the npm dependencies into vendor/ so the page
// works without a bundler (file:// and GitHub Pages). Run: npm run vendor
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const root = join(dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, '$1')), '..');
const out = join(root, 'vendor');
mkdirSync(out, { recursive: true });
const pkgDir = (name) => dirname(require.resolve(name + '/package.json'));

// ZzFX ships as an ES module -> turn it into a classic script exposing window.zzfx / window.ZZFX
const zz = readFileSync(join(pkgDir('zzfx'), 'ZzFX.js'), 'utf8')
  .replace(/^export\s+/gm, '')
  .replace(/audioContext:\s*new AudioContext,/, 'audioContext: new (window.AudioContext || window.webkitAudioContext)(),');
writeFileSync(join(out, 'zzfx.js'), '// Generated by scripts/vendor.mjs from the zzfx npm package (MIT).\n(function () {\n' + zz +
  '\nwindow.zzfx = zzfx; window.ZZFX = ZZFX; window.ZZFXSound = ZZFXSound;\n})();\n');

// three.js (+ MapControls) bundled by esbuild into one classic script exposing window.THREE
const esbuild = await import('esbuild');
await esbuild.build({
  stdin: {
    contents: "export * from 'three'; export { MapControls } from 'three/examples/jsm/controls/MapControls.js';",
    resolveDir: root, loader: 'js',
  },
  bundle: true, format: 'iife', globalName: 'THREE', minify: true, legalComments: 'none',
  outfile: join(out, 'three.js'),
  banner: { js: '// three.js (MIT) bundled by scripts/vendor.mjs' },
});

// Nunito (rounded, cozy; latin subset covers ä ö ü)
const font = join(pkgDir('@fontsource/nunito'), 'files');
for (const w of [400, 700, 800]) {
  const f = 'nunito-latin-' + w + '-normal.woff2';
  try { copyFileSync(join(font, f), join(out, f)); } catch (e) { console.warn('missing', f); }
}
console.log('vendor/ updated');
